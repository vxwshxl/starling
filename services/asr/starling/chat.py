"""Retrieval-grounded answering: the brain behind POST /chat.

This is what used to be the PHASE 2 SEAM in pipeline.py. The full design is

    ASR -> translate to English -> retrieve + generate -> translate back -> TTS

and everything here is the middle. The two translation legs are NOT built:
IndicTrans2 needs a slow tokenizer that transformers 5 removed, and OmniVoice
pins transformers>=5.3.0, so the two cannot coexist in one environment. See
`translation_available()` for how that is reported rather than hidden.

The consequence, stated plainly because it decides what the product can
honestly claim: questions are answered in the language the model can actually
read. For Bodo, Manipuri and Santali that means speech still works end to end
but the answer is not in the speaker's language yet.
"""

from __future__ import annotations

import logging
import re
from dataclasses import dataclass, field
from typing import Literal

from . import llm, retrieval
from .timing import Timings

logger = logging.getLogger("starling.chat")

#: Shown when retrieval finds nothing. Deliberately not generated by the model:
#: the one moment we are certain we have no grounding is the worst possible
#: moment to let it improvise. It names concrete examples, because "covers
#: health and government services" is too abstract to act on -- a person who
#: gets this needs to know what to type instead.
NO_ANSWER = (
    "I do not have information about that. I can only answer from a small "
    "offline knowledge base covering health, government services, education "
    "and rural livelihoods -- things like fever, diarrhoea, pregnancy care, "
    "ration cards, job cards, school admission, pensions or safe drinking "
    "water. For anything urgent, please contact your nearest health centre "
    "or ASHA worker."
)

#: Answer to a greeting. Retrieval cannot help here -- "hi" shares no words
#: with any passage -- so without this the very first thing a new user typed
#: got a refusal, which reads as the assistant being broken rather than
#: careful. Fixed text, not generated: there is nothing to ground it in.
GREETING = (
    "Hello. I am Starling. I answer questions about health, government "
    "services, education and rural livelihoods from a knowledge base held on "
    "this machine, so nothing you say leaves it. Ask me something like \"my "
    "child has loose motion since morning\" or \"how do I apply for a job "
    "card\"."
)

THANKS = (
    "You are welcome. Ask me anything else about health, government services, "
    "education or rural livelihoods."
)

#: Small talk, matched before retrieval. Anchored whole-string and kept
#: deliberately narrow: a phrase long enough to carry a real question must
#: never be swallowed here, so "hello, my child has a fever" falls through to
#: retrieval as it should.
_SMALL_TALK: tuple[tuple[re.Pattern[str], str], ...] = (
    (
        re.compile(
            r"^(hi|hii+|hey+|hello+|hlo|yo|namaste|namaskar|nomoskar|salaam|"
            r"good\s+(morning|afternoon|evening)|are\s+you\s+there)"
            r"([\s,!.?]+(there|starling))?$"
        ),
        GREETING,
    ),
    (
        re.compile(r"^(thanks?|thank\s+you|thx|ok(ay)?|got\s+it|nice|good)$"),
        THANKS,
    ),
    (
        re.compile(
            r"^((what|who)\s+(are|can)\s+you(\s+do)?|what\s+do\s+you\s+do|"
            r"what\s+can\s+(you|i)\s+ask|help|how\s+does\s+this\s+work)$"
        ),
        GREETING,
    ),
)


def _small_talk(question: str) -> str | None:
    """Fixed reply for a greeting or pleasantry, or None to answer normally."""
    normalised = re.sub(r"[\s]+", " ", question.strip().lower()).strip(" !.?,")
    for pattern, reply in _SMALL_TALK:
        if pattern.fullmatch(normalised):
            return reply
    return None


@dataclass
class Source:
    id: str
    title: str
    sector: str
    score: float


@dataclass
class ChatResult:
    text: str
    """The answer, in English."""

    sources: list[Source] = field(default_factory=list)
    """Passages the answer was built from. Empty means it was refused."""

    grounded: bool = True
    """False when the text did not come from retrieved passages."""

    kind: Literal["answer", "refusal", "small_talk"] = "answer"
    """Why the text says what it says. `grounded` alone cannot distinguish a
    refusal from a greeting -- both are ungrounded, but only one of them is
    the assistant declining to help, and the UI must not label a hello as
    'not covered by the knowledge base'."""

    language: str = "en"
    """Language the answer is actually written in, which is not necessarily
    the language the question was asked in -- see the module docstring."""

    warnings: list[str] = field(default_factory=list)


def translation_available() -> bool:
    """Whether the indic<->English legs of the cascade exist.

    Hard-coded False rather than probed: the blocker is a dependency conflict,
    not a missing download, so there is nothing to detect at runtime. When
    translation lands, this becomes a real check.
    """
    return False


def answer(
    question: str,
    language_code: str = "en",
    timings: Timings | None = None,
) -> tuple[ChatResult, Timings]:
    """Answer a question from the knowledge base.

    `language_code` is the language the question was asked in. It does not yet
    change the answer's language; it is used to warn honestly when it should
    have and could not.
    """
    timings = timings or Timings()
    warnings: list[str] = []

    if not question.strip():
        raise ValueError("Cannot answer an empty question.")

    if language_code not in ("en", "") and not translation_available():
        warnings.append(
            "Translation is not available yet, so this answer is in English "
            "rather than the language you asked in."
        )

    # Before retrieval, not after: a greeting shares no vocabulary with any
    # passage, so BM25 would return nothing and the refusal path would claim
    # the knowledge base does not cover "hello" -- true, and useless.
    if (reply := _small_talk(question)) is not None:
        logger.info("small talk: %r", question[:40])
        return (
            ChatResult(
                text=reply,
                sources=[],
                grounded=False,
                kind="small_talk",
                warnings=warnings,
            ),
            timings,
        )

    with timings.stage("retrieve"):
        hits = retrieval.search(question)

    if not hits:
        logger.info("no passage matched %r; refusing rather than guessing", question[:60])
        return (
            ChatResult(
                text=NO_ANSWER,
                sources=[],
                grounded=False,
                kind="refusal",
                warnings=warnings,
            ),
            timings,
        )

    with timings.stage("generate"):
        text = llm.answer(question, [h.passage.text for h in hits])

    result = ChatResult(
        text=text,
        sources=[
            Source(
                id=h.passage.id,
                title=h.passage.title,
                sector=h.passage.sector,
                score=round(h.score, 2),
            )
            for h in hits
        ],
        grounded=True,
        warnings=warnings,
    )
    logger.info(
        "answered %r from %s", question[:50], ", ".join(s.id for s in result.sources)
    )
    return result, timings
